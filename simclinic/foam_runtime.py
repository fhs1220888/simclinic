"""Run-bound provenance for the pinned serial Foundation 10 agent integration.

These hooks are for observed fresh runs, never for relabelling imported outputs.
The manifest is trusted collector metadata, not a signature or script sandbox.
"""
from contextlib import contextmanager
import hashlib
import json
import math
from pathlib import Path
import shutil
import uuid

from .collection import digest
from .core.record import load_record
from .core.report import write_json
from .result_guard import ResultRejected, read_verified_result


def _files(folder):
    if folder.is_symlink():
        raise ResultRejected("unsafe_path", "Case inputs/outputs cannot be symlinks.")
    for path in sorted(folder.rglob("*")):
        if path.is_symlink():
            raise ResultRejected("unsafe_path", "Case inputs/outputs cannot be symlinks.")
        if path.is_file():
            yield path


def inputs(case):
    case = Path(case).resolve()
    manifest = {}
    for name in ("0", "constant", "system"):
        for path in _files(case / name):
            relative = path.relative_to(case)
            # polyMesh is generated by Allrun, so capture it as an output.
            if relative.parts[:2] != ("constant", "polyMesh"):
                manifest[str(relative)] = hashlib.sha256(path.read_bytes()).hexdigest()
    allrun = case / "Allrun"
    if allrun.is_symlink() or not allrun.is_file():
        raise ResultRejected("missing_input", "A regular Allrun file is required.")
    manifest["Allrun"] = hashlib.sha256(allrun.read_bytes()).hexdigest()
    if not (case / "0/U").is_file() or not (case / "0/p").is_file():
        raise ResultRejected("unsupported_case", "The integration requires serial incompressible U/p inputs.")
    return manifest


def _times(case):
    result = []
    for path in case.iterdir():
        try:
            time = float(path.name)
        except ValueError:
            continue
        if math.isfinite(time) and time > 0 and path.is_dir():
            if path.is_symlink():
                raise ResultRejected("unsafe_path", "Time directories cannot be symlinks.")
            result.append(path)
    return sorted(result, key=lambda path: float(path.name))


def begin_run(case_dir):
    case = Path(case_dir).resolve()
    manifest = inputs(case)
    # Fail closed on cleanup failure; old time directories must not be adopted.
    for path in _times(case):
        shutil.rmtree(path)
    run_id = uuid.uuid4().hex
    context = dict(run_id=run_id, input_version="sha256:" + digest(manifest))
    directory = case / ".simclinic/native" / run_id
    directory.mkdir(parents=True, exist_ok=False)
    data = dict(schema_version="1.0", record_id="native-" + run_id, synthetic=False,
                **context, input_manifest=manifest, collection_status="in_progress",
                environment={"distribution": "OpenFOAM Foundation", "version": "10", "solver": "simpleFoam"},
                agent={"name": "Foam-Agent", "commit": "bfb7f791f77438ff90c1a39ff398739ee97bcc67"},
                task={"id": "native-execution", "objective": "Observe native execution and postprocessing; CFD acceptance supplied separately.", "required_preflight": [], "acceptance": []},
                coverage=dict(tools=False, decisions=False, references=False, acceptance=False),
                metrics=dict(wall_seconds=None, solver_seconds=None, model_tokens=None, model_cost=None),
                events=[], artifacts=[])
    write_json(directory / "record.json", data)
    write_json(case / ".simclinic/native/current.json", dict(**context, status="in_progress"))
    return context


def finish_run(case_dir, context, errors):
    case = Path(case_dir).resolve()
    path = case / ".simclinic/native" / context["run_id"] / "record.json"
    data = load_record(path, case).data
    if "sha256:" + digest(inputs(case)) != context["input_version"]:
        errors = list(errors) + [{"error_content": "Inputs changed during execution; provenance rejected."}]
    times = _times(case)
    if not errors and (not times or any(not (times[-1] / field).is_file() for field in ("U", "p"))):
        errors = [{"error_content": "Fresh U/p solver outputs are missing."}]
    data["execution_errors"] = errors
    data["collection_status"] = "failed" if errors else "complete"
    code = next((error["exit_code"] for error in errors if isinstance(error, dict) and type(error.get("exit_code")) is int), None)
    data["events"].append(dict(id="native-solve", kind="tool", **context,
        operation="Allrun", phase="solve", outcome="fail" if errors else "pass",
        exit_code=code if errors else 0, arguments={"script": "Allrun"},
        input_fingerprint=digest(data["input_manifest"]), error_category="execution_failure" if errors else None))
    if not errors:
        selected = [case / relative for relative in data["input_manifest"]]
        selected.extend(_files(case / "constant/polyMesh"))
        for directory in times:
            selected.extend(_files(directory))
        for item in sorted(set(selected)):
            data["artifacts"].append(dict(id=str(item.relative_to(case)), path=str(item.relative_to(case)),
                **context, role="reader_input", sha256=hashlib.sha256(item.read_bytes()).hexdigest()))
        data["output_times"] = [item.name for item in times]
    write_json(path, data)
    write_json(case / ".simclinic/native/current.json", dict(**context, status=data["collection_status"]))
    return errors


def current_record(case_dir, context):
    case = Path(case_dir).resolve()
    if not isinstance(context, dict) or any(not isinstance(context.get(key), str) or not context[key] for key in ("run_id", "input_version")):
        raise ResultRejected("unknown_expected_identity", "Current orchestrator run/input is required.")
    run_id = context["run_id"]
    if len(run_id) != 32 or any(c not in "0123456789abcdef" for c in run_id):
        raise ResultRejected("unknown_expected_identity", "Invalid orchestrator run ID.")
    try:
        pointer = json.loads((case / ".simclinic/native/current.json").read_text())
    except (OSError, ValueError) as exc:
        raise ResultRejected("missing_provenance", "No generation-time manifest is available.") from exc
    if pointer.get("run_id") != run_id:
        raise ResultRejected("stale_run", "A newer run replaced this result context.")
    if pointer.get("input_version") != context["input_version"]:
        raise ResultRejected("stale_input", "The expected input version differs.")
    if pointer.get("status") != "complete":
        raise ResultRejected("incomplete_run", "Only a completed fresh execution can be postprocessed.")
    if "sha256:" + digest(inputs(case)) != context["input_version"]:
        raise ResultRejected("stale_input", "Case inputs changed after this execution.")
    record = load_record(case / ".simclinic/native" / run_id / "record.json", case)
    if record.data.get("collection_status") != "complete":
        raise ResultRejected("incomplete_run", "The run manifest is not complete.")
    if [p.name for p in _times(case)] != record.data.get("output_times"):
        raise ResultRejected("untracked_output", "Time directories differ from the observed run.")
    return record


@contextmanager
def verified_workspace(case_dir, context):
    case = Path(case_dir).resolve()
    record = current_record(case, context)
    # Consume exactly the verified bytes, never reopen originals for the reader.
    payloads = {a["path"]: read_verified_result(record, a["id"], context["run_id"], context["input_version"])
                for a in record.data["artifacts"] if a.get("role") != "visualization"}
    attempt = case / ".simclinic/native" / context["run_id"] / "postprocessing" / uuid.uuid4().hex
    work = attempt / "case"
    work.mkdir(parents=True)
    for relative, payload in payloads.items():
        target = work / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)
    # .foam is an empty descriptor; it is not evidence of solver execution.
    (work / "case.foam").touch()
    marker = dict(**context, source_case=str(case), output_times=record.data["output_times"],
                  input_files={k: hashlib.sha256(v).hexdigest() for k, v in payloads.items()})
    write_json(attempt / "verified.json", marker)
    try:
        yield work
        verify_workspace(work)
    except Exception as exc:
        write_json(attempt / "outcome.json", dict(allowed=False, code=getattr(exc, "code", "postprocess_error"), message=str(exc)))
        raise


def verify_workspace(case_dir):
    work = Path(case_dir).resolve()
    try:
        marker = json.loads((work.parent / "verified.json").read_text())
    except (OSError, ValueError) as exc:
        raise ResultRejected("unverified_workspace", "Render only from a verified run snapshot.") from exc
    current_record(marker["source_case"], marker)
    if [p.name for p in _times(work)] != marker["output_times"]:
        raise ResultRejected("snapshot_changed", "Verified snapshot time directories changed.")
    for relative, sha in marker["input_files"].items():
        path = work / relative
        if path.is_symlink() or work not in path.resolve().parents or not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != sha:
            raise ResultRejected("snapshot_changed", "Verified reader inputs changed.")
    return marker


def record_image(case_dir, image_path):
    work = Path(case_dir).resolve()
    marker = verify_workspace(work)
    image = Path(image_path)
    if image.is_symlink() or work not in image.resolve().parents or not image.is_file():
        raise ResultRejected("unsafe_output", "The image must be generated inside the verified workspace.")
    payload = image.read_bytes()
    if not payload.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ResultRejected("invalid_image", "Expected a newly generated PNG.")
    outcome = dict(**{key: marker[key] for key in ("run_id", "input_version")}, allowed=True,
                   path=str(image.resolve()), sha256=hashlib.sha256(payload).hexdigest())
    source = Path(marker["source_case"])
    record = current_record(source, marker)
    identity = {key: marker[key] for key in ("run_id", "input_version")}
    artifact_id = "png-" + work.parent.name
    record.data["artifacts"].append(dict(id=artifact_id, path=str(image.resolve().relative_to(source)),
        **identity, role="visualization", sha256=outcome["sha256"]))
    for relative in marker["input_files"]:
        record.data["events"].append(dict(id="ref-" + str(len(record.data["events"])), kind="reference",
            **identity, artifact_id=relative, consumer="verified PyVista snapshot"))
    record.data["events"].append(dict(id="render-" + work.parent.name, kind="tool", **identity,
        operation="PyVista", phase="postprocess", outcome="pass", exit_code=0,
        input_fingerprint=digest(marker["input_files"]), error_category=None,
        arguments={"workspace": str(work)}, output_artifact=artifact_id))
    write_json(Path(record.source), record.data)
    write_json(work.parent / "outcome.json", outcome)
    return outcome
